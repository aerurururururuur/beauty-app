/** 未收录真实色号的产品：生成占位块，标注「待补」而不是编造色号 */
export function placeholderShades(count = 6) {
  const palette = ['#f2d6d2', '#e8b9ae', '#dd9d99', '#c97b7b', '#b06a5f', '#9c6a55'];
  return Array.from({ length: count }, (_, i) => ({
    code: `#${i + 1}`,
    name: '色号待补',
    hex: palette[i % palette.length],
    hexApprox: true,
    tone: '待补',
    toneKey: 'neutral',
    lightness: '—',
    saturation: '—',
  }));
}

/** 取某产品的色号数组；没有收录时返回占位块 */
export function shadesOf(productId, fallbackCount = 6) {
  const entry = SHADE_LIBRARY[productId];
  if (!entry) return { label: '', shades: placeholderShades(fallbackCount) };
  return { label: entry.label, shades: entry.shades };
}
