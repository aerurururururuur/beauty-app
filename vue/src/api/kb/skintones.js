/**
 * 肤色档库 —— 数据来源：用户口述的肤色习惯分类（黄一白 / 冷白皮 / 橄榄皮 …）
 *
 * 为什么需要它：
 *   上传照片必然存在色差（光线、白平衡、滤镜），AI 图片分析只能给「建议档」，
 *   最终肤色档位必须由用户在这份固定档位里确认，生成时按档位选色号。
 *
 * 前端只负责「展示档位 + 把选中的档位 id 交给后端」，不做肤色推理。
 */

/** T = 肤色档：tone 色调倾向，desc 识别口诀，hex 示意肤色（仅用于色点，不是测量值） */
const T = (id, name, tone, desc, hex) => ({ id, name, tone, desc, hex });

export const SKIN_TONES = [
  T('cool-fair', '冷白皮', '冷调', '血管偏蓝紫，晒后先红不黑，银饰更衬', '#F4E3DE'),
  T('pink-fair', '粉一白', '冷调', '白皙带粉感，两颊容易泛红', '#F6E2DA'),
  T('yellow-1', '黄一白', '暖调', '暖调里最白的一档，亚洲最常见', '#F3E3CF'),
  T('yellow-2', '黄二白', '暖调', '自然肤色，不白不黑，素颜不偏灰', '#EDD8BE'),
  T('olive', '橄榄皮', '橄榄调', '带一点绿调，室内光下容易显暗显黄', '#E5D5B4'),
  T('yellow-dark', '黄黑皮', '暖调', '偏深的暖调肤色，晒后明显加深', '#DDBE98'),
  T('wheat', '小麦色', '暖调', '健康暖棕，户外感强', '#D2AE82'),
  T('deep', '深棕皮', '中性偏暖', '深肤色，高饱和色号更显气色', '#BD9668'),
];

/** 按 id 取肤色档；未命中返回 null，交由页面处理「未选择」态 */
export function skinToneById(id) {
  return SKIN_TONES.find((t) => t.id === id) || null;
}
