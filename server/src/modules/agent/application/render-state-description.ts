/**
 * agent/application/render-state-description.ts —— 把「出图这件事走到哪一步了」讲成一行字。
 *
 * ★ **为什么专门为它写一句**:出图是全流程**唯一需要用户点确认**的环节,
 *   而模型过去**看不到它的状态**——`## 当前状态` 里只有「已知需求 + 妆面」。
 *   于是在"妆面聊定了、用户还没说要出图"的那一轮,模型手里没有任何东西能告诉它
 *   "现在没有确认框在等",它只能照句式说。
 *
 * **实测到的翻车(2026-09-16,真实模型 `qwen-flash`)**:用户说「好,就这样吧。我皮肤偏干」,
 * 模型回了一句「确认之后我就开始出图」——而那一轮它**根本没调 `render_look`**,
 * 会话里没有任何确认框(`pendingRender` 为 null)。用户于是去找一张不存在的卡片。
 *
 * ★ **根因不在"模型不听话",在我们把一句关于状态的话交给了没有状态的人。**
 *   那句话被**原样引在 `RENDER_LOOK` 的工具描述里**(模型每一轮都读得到那段),
 *   规则 6 又当示范句引了一遍——它拿到的是**句式**,不是**前提**。
 *   而 `## 当前状态` 里一个字都没提出图走到哪一步,所以它连"现在该不该说"
 *   都无从判断,只能照句式说。
 *
 *   所以修法是两处,缺一不可:
 *   ① 这里把状态补上(它看得见"此刻没有确认框");
 *   ② 规则 6 与工具描述把句式改成**有前提的**(那句话必须和 `render_look` 的调用
 *      绑在同一条回复里)。只做 ① 模型仍会照抄句式;只做 ② 它猜不出当下该不该说。
 *
 * ⚠️ **"有一个确认框在等"那一支不是给当轮看的,是给下一轮看的。**
 *   带 `pending` 的那一轮,循环**当场就停了**(`agent-loop.ts` ⑦),不会再调 LLM;
 *   等用户不点确认、改口说别的,下一轮才会读到这一行。那时它该做的是**别再重复提议**。
 *   而当轮那句回执,靠的是"和工具调用绑在同一条回复里"这条前提,不是靠这一行。
 *
 * ★ **口径与 `toSessionView` 的 `pendingRender` 同源**:都用 `danglingToolUses`。
 *   不共用的话会出现「视图说有确认框、提示词说没有」这种自相矛盾——
 *   而这两处**判断的是同一件事**,只是分别给前端和给模型看。
 *
 * ⚠️ **故意不报"还能出几张"**:那需要把 `maxRenders` 也搬进来,而配额的真出处是
 *   `rendersLeft()` + `render_look` 的那道检查。多一份就多一处能对不上的地方;
 *   而且**超限时那个工具自己会说**(它返回「这辈子只剩 0 次」这类说明),
 *   模型拿到的是准确的当下判词,比提示词里一个可能已经过期的数字强。
 *   同 `session.ts` 那条「派生出来的东西不存第二遍」的取舍。
 *
 * ✏️ **2026-09-16:那一句"此刻没有确认框在等用户点"读起来变了味,改措辞前先看这里。**
 *   出图现在**多了一条入口**——界面按状态自己摆一条带按钮的消息(`renderOffer`),
 *   用户点它就直接出图,整个过程中**模型一个字都不用说**(见 `confirm-render.ts`)。
 *   所以"没有确认框在等"**不等于"出不了图"、更不等于"用户没别的路"**:
 *   那只是说**模型这边**没有待办的提议。它照样可以自己调 `render_look` 提议出图
 *   (那条路一字未改),但用户想要图时**不必等它开口**。
 *   ⚠️ 这一行**本次一个字都没改**(`v11` 已被真实模型跑过,按本仓库的判据不能再改正文),
 *   所以上面那句是给**下一个人**看的:真要改这一行时,别写成让模型以为
 *   "现在什么都做不了"的口径。
 */
import { TOOL_NAMES } from '../domain/tools/definitions.js';
import { danglingToolUses } from '../domain/entities/message.js';
import type { Session } from '../domain/entities/session.js';

/**
 * 渲染出图管线的当前状态。**要能被模型直接照字面用**,所以每一格都说清"有/没有",
 * 不留"没提就是没有"这种要靠推断的空白——推断正是这次翻车的来源。
 */
export function describeRenderState(session: Session): string {
  const pending = danglingToolUses(session.messages).some(
    (call) => call.name === TOOL_NAMES.renderLook,
  );

  // ★ 有待确认时,`faceRef` 必然在(工具自己挡过),所以这一支不用再报照片。
  if (pending) {
    return (
      '出图:**此刻有一个确认框正等用户点**,还没开始生成、也还没花钱。' +
      '只等她点,别重复提议、也别自己动手。'
    );
  }

  const photo = session.faceRef
    ? '已有她的照片'
    : '**还没有她的照片**(所以现在出不了图,得先请她传一张正面照)';
  const rendered =
    session.renders.length === 0
      ? '还没出过图'
      : `已经出过 ${session.renders.length} 张图`;
  // ⚠️ 末尾那句是这次修复的重点:让模型看得见"**此刻没有**确认框"。
  //    没有这一句,它就只能靠自己猜——而它猜错过一次。
  return `出图:${photo};${rendered};此刻**没有**确认框在等用户点。`;
}
