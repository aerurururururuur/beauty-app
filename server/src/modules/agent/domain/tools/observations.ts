/**
 * agent/domain/tools/observations.ts —— ★ 几段**回给模型的 observation** 里,被第二处依赖的那几个开头。
 *
 * ── 为什么需要一个单独的文件 ──────────────────────────────────────────────────
 *
 * 这些字符串本来长在使用它们的地方(`application/tools/render-look.ts`、
 * `application/usecases/attach-photo.ts`)。但阶段 3 之后多了一个读者:
 * **离线演示驱动**(`infrastructure/llm/demo-llm.ts`)要继续演下去,就必须知道
 * "这次到底出图了没有""照片到手了没有",而它唯一能看到的就是这些 `tool_result` 的正文。
 *
 * 让它自己抄一遍字符串是**最坏的那种重复**:两份不会同时改,而它们一旦漂开,
 * 演示会在**最不该出错的地方**静默演错——出图成功了却按"被拒"接话。
 * 所以搬到这里,谁用谁 import。
 *
 * ★ **为什么放在 `domain/tools/` 而不是留在原处**:端口与契约文本本来就归 domain
 *   (`domain/tools/definitions.ts` 装的就是"给模型看的工具描述",是同一类东西)。
 *   放在这里,`application` 与 `infrastructure` **都是向下依赖**,不出现
 *   「infrastructure 反向 import application」那种把分层绕过去的写法。
 *
 * ⚠️ **只导出前缀,不导出整句**。那两句里有 markdown 强调号
 *   (`所以这次**没有生成任何图**`),整句比对会被那两个 `**` 绊倒;
 *   前缀取到强调号之前,已经足够把"出成了"和"被拒了"分开。
 */

